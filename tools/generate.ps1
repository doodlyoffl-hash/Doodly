# Default meta description (unchanged pages keep this byte-for-byte).
$defaultDesc = 'DOODLY — fresh A2 buffalo milk, delivered daily in glass bottles.'
# Per-route rich SEO / social-share metadata. Routes NOT listed here render the
# generic head exactly as before (no diff). Add a route to give it OG + Twitter
