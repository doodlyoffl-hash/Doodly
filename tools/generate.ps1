# Routes that must never be indexed (private, token-gated pages).
$noindexRoutes = @('rewards/claim')
function Build-HeadExtra($s) {
  $ld = '{"@context":"https://schema.org","@type":"WebPage","name":"' + $s.ogTitle + '","description":"' + $s.desc + '","url":"' + $s.canonical + '","publisher":{"@type":"Organization","name":"DOODLY","logo":"https://doodly.in/assets/img/logo.png"}}'
  $lines = @(
    "  <link rel=""canonical"" href=""$($s.canonical)"">",
    "  <meta property=""og:type"" content=""website"">",
    "  <meta property=""og:site_name"" content=""DOODLY"">",
    "  <meta property=""og:title"" content=""$($s.ogTitle)"">",
    "  <meta property=""og:description"" content=""$($s.desc)"">",
    "  <meta property=""og:url"" content=""$($s.canonical)"">",
    "  <meta property=""og:image"" content=""$($s.image)"">",
    "  <meta property=""og:image:width"" content=""1200"">",
    "  <meta property=""og:image:height"" content=""630"">",
    "  <meta name=""twitter:card"" content=""summary_large_image"">",
    "  <meta name=""twitter:title"" content=""$($s.ogTitle)"">",
    "  <meta name=""twitter:description"" content=""$($s.desc)"">",
    "  <meta name=""twitter:image"" content=""$($s.image)"">",
    "  <script type=""application/ld+json"">$ld</script>"
  )
  return "`n" + ($lines -join "`n")
}

# Refresh the minified JS artifacts (assets/js/*.min.js) the pages reference.
# Resilient: minify.mjs exits 0 (keeping existing committed .min.js) if node/terser is absent.
try { & node (Join-Path $Root 'tools/minify.mjs') } catch { Write-Host "  (minify skipped: $_)" -ForegroundColor Yellow }

# Content-hash build id → stamped as ?v=<id> on every .min.js/.min.css URL so those
# assets are safely immutable-long-cacheable (the URL changes only when content changes).
$buildId = ''
try { $buildId = (Get-Content (Join-Path $Root 'assets/build-id.txt') -Raw).Trim() } catch { }

$utf8 = New-Object System.Text.UTF8Encoding($false)
$count = 0
$bySurface = @{}

foreach ($m in $rx.Matches($manifest)) {
  $route   = $m.Groups['route'].Value
  $title   = $m.Groups['title'].Value
  $surface = $m.Groups['surface'].Value
  $file    = if ($route -eq 'home') { 'index.html' } else { "$route.html" }
  $path    = Join-Path $Root $file
  $dir     = Split-Path $path -Parent
  if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }

  $desc = $defaultDesc
  $headExtra = ''
  if ($noindexRoutes -contains $route) { $headExtra = "`n  <meta name=""robots"" content=""noindex, nofollow"">" }
  elseif ($seo.ContainsKey($route)) { $desc = $seo[$route].desc; $headExtra = Build-HeadExtra $seo[$route] }

  $adminBlock = if ($adminSurfaces -contains $surface) { $adminScripts + "`n" } else { '' }
  $html = $template.Replace('{{ROUTE}}', $route).Replace('{{TITLE}}', $title).Replace('{{DESC}}', $desc).Replace('{{HEAD_EXTRA}}', $headExtra).Replace('{{ADMIN_SCRIPTS}}', $adminBlock)
  if ($buildId) { $html = $html.Replace('.min.js"', ".min.js?v=$buildId`"").Replace('.min.css"', ".min.css?v=$buildId`"") }
  [System.IO.File]::WriteAllText($path, $html, $utf8)
  $count++
  if (-not $bySurface.ContainsKey($surface)) { $bySurface[$surface] = 0 }
  $bySurface[$surface]++
}

Write-Host "DOODLY - generated $count pages:" -ForegroundColor Green
$bySurface.GetEnumerator() | Sort-Object Name | ForEach-Object { Write-Host ("  {0,-9} {1}" -f $_.Key, $_.Value) }
